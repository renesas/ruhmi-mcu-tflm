#ifndef MODEL_WRAPPER_H
#define MODEL_WRAPPER_H

#include "model.h"
#include <stdint.h>

/* Thin adapter between the application and the TFLM runtime API generated by the RUHMI TFLM backend (model.h). */

static inline int model_init(void) {
    return ModelInit();
}

static inline uint8_t* model_input_ptr(void) {
    return (uint8_t*) GetModelInputPtr_image_input();
}

/* 6x6 grid output (stride 32) */
static inline uint8_t* model_output0_ptr(void) {
    return (uint8_t*) GetModelOutputPtr_Identity();
}

/* 12x12 grid output (stride 16) */
static inline uint8_t* model_output1_ptr(void) {
    return (uint8_t*) GetModelOutputPtr_Identity_1();
}

/* Returns 0 on success */
static inline int model_invoke(void) {
    RunModel(false);
    return GetLastInvokeStatus();
}

#endif // MODEL_WRAPPER_H
