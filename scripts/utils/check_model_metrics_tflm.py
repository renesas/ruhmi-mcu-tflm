"""
check_model_metrics_tflm.py -- Model metrics for TFLM-compiled outputs.

Parses the artifacts generated by scripts/mcu_compile_tflm.py and reports
a model metrics table.

MACs for CPU path are computed directly from the INT8 .tflite flatbuffer
using per-op formulas. No TensorFlow dependency required.
"""

__version__ = "1.0.0"

import argparse
import json
import re
import struct
import sys
from pathlib import Path


# =============================================================================
# Directory Layout Detection
# =============================================================================

# model.cc / model_<suffix>.cc; the generated data header follows the same suffix.
_MODEL_CC_RE = re.compile(r'^model(?:_(.+))?\.cc$')


def _normalize_suffix(suffix: str) -> str:
    """Normalize a suffix the same way scripts/mcu_compile_tflm.py does."""
    return ''.join(c if c.isalnum() else '_' for c in str(suffix).strip()).strip('_')


def _find_models(src_dir: Path) -> dict:
    """Map each generated model's suffix ('' for none) to (model*.cc, model_data*.h)."""
    models = {}
    for cc in sorted(src_dir.glob("model*.cc")):
        m = _MODEL_CC_RE.match(cc.name)
        if not m:
            continue
        sfx = m.group(1) or ''
        models[sfx] = (cc, src_dir / (f"model_data_{sfx}.h" if sfx else "model_data.h"))
    return models


def _describe_models(models: dict) -> str:
    return ', '.join(f"'{s}'" if s else "(no suffix)" for s in models)


def find_tflm_dirs(root: Path, suffix: str = None) -> dict:
    """
    Locate key files from one model output folder written by
    scripts/mcu_compile_tflm.py (the folder that contains deploy/).

    The deploy/src folder itself is also accepted. When deploy/src holds
    several models, select one with ``suffix``.

    Returns a dict with:
        root          Path  - model output folder
        src_dir       Path  - <root>/deploy/src
        suffix        str   - suffix of the selected model ('' for none)
        model_count   int   - number of models found in src_dir
        model_cc      Path  - model*.cc
        model_data_h  Path  - model_data*.h
        vela_report   Path | None
        tflite_path   Path | None  - pre-Vela .tflite for MAC counting
        is_npu        bool
    """
    root = Path(root)
    if root.name == "src" and root.parent.name == "deploy":
        root = root.parent.parent

    src_dir = root / "deploy" / "src"
    if not src_dir.is_dir():
        message = (f"No deploy/src folder under {root}.\n"
                   "Pass a single model output folder, for example "
                   "deploy_output/<model>_NPU_tflm/.")
        found = sorted(p.parent.parent.name for p in root.glob("*/deploy/src") if p.is_dir())
        if found:
            message += "\nModel output folders found here: " + ", ".join(found)
        raise FileNotFoundError(message)

    models = _find_models(src_dir)
    if not models:
        raise FileNotFoundError(f"No model*.cc found in {src_dir}")

    if suffix is not None:
        key = _normalize_suffix(suffix)
        if key not in models:
            raise FileNotFoundError(
                f"No model with suffix '{suffix}' in {src_dir}. "
                f"Available: {_describe_models(models)}")
    elif len(models) == 1:
        key = next(iter(models))
    else:
        raise ValueError(
            f"{src_dir} contains {len(models)} models ({_describe_models(models)}). "
            "Select one with --suffix.")

    model_cc, model_data_h = models[key]
    if not model_data_h.exists():
        raise FileNotFoundError(f"{model_data_h.name} not found in {src_dir}")

    is_npu = "ethosu.h" in model_cc.read_text(encoding="utf-8")

    vela_report = None
    if is_npu:
        vela_report = root / "vela" / "vela_report.txt"
        if not vela_report.exists():
            raise FileNotFoundError(
                f"NPU build detected but vela/vela_report.txt not found under {root}.\n"
                "Re-run scripts/mcu_compile_tflm.py to regenerate it."
            )

    # Pre-Vela model for MAC counting: the quantized model if the compiler
    # converted one, otherwise the reference copy of the input model.
    tflite_path = None
    for d in (root / "quantization", root / "reference"):
        if d.is_dir():
            hits = [h for h in sorted(d.glob("*.tflite")) if "_vela" not in h.name]
            if hits:
                tflite_path = hits[0]
                break

    return {
        "root": root,
        "src_dir": src_dir,
        "suffix": key,
        "model_count": len(models),
        "model_cc": model_cc,
        "model_data_h": model_data_h,
        "vela_report": vela_report,
        "tflite_path": tflite_path,
        "is_npu": is_npu,
    }


# =============================================================================
# Parse Generated C Headers
# =============================================================================

def parse_arena_size(model_cc: Path) -> int:
    text = model_cc.read_text(encoding="utf-8")
    m = re.search(r'#define\s+TENSOR_ARENA_SIZE(?:_\w+)?\s+(\d+)', text)
    if not m:
        raise ValueError(f"TENSOR_ARENA_SIZE not found in {model_cc}")
    return int(m.group(1))


def parse_model_data_size(model_data_h: Path) -> int:
    text = model_data_h.read_text(encoding="utf-8")
    m = re.search(r'#define\s+MODEL_DATA_SIZE(?:_\w+)?\s+(\d+)', text)
    if not m:
        raise ValueError(f"MODEL_DATA_SIZE not found in {model_data_h}")
    return int(m.group(1))


def parse_op_list(model_cc: Path) -> list:
    text = model_cc.read_text(encoding="utf-8")
    return re.findall(r'resolver\.(Add\w+)\s*\(', text)


def parse_io_info(model_cc: Path):
    text = model_cc.read_text(encoding="utf-8")
    n_in  = len(set(re.findall(r'interpreter->input\((\d+)\)', text)))
    n_out = len(set(re.findall(r'interpreter->output\((\d+)\)', text)))
    return n_in, n_out


# =============================================================================
# Parse Vela Report (NPU path)
# =============================================================================

def _vela_size_to_bytes(value_str: str, unit_str: str):
    """Convert a Vela size figure to bytes; None for an unrecognized unit."""
    multipliers = {
        'B': 1, 'BYTES': 1,
        'KB': 1024, 'KIB': 1024,
        'MB': 1024 ** 2, 'MIB': 1024 ** 2,
        'GB': 1024 ** 3, 'GIB': 1024 ** 3,
    }
    multiplier = multipliers.get(unit_str.strip().upper())
    return None if multiplier is None else int(float(value_str) * multiplier)


def parse_vela_report(vela_report: Path) -> dict:
    text = vela_report.read_text(encoding="utf-8")

    def find(pattern):
        return re.search(pattern, text)

    result = {}

    m = find(r'Accelerator configuration\s+(\S+)')
    result['accel_config'] = m.group(1) if m else 'Unknown'
    m = find(r'System configuration\s+(\S+)')
    result['sys_config'] = m.group(1) if m else 'Unknown'
    m = find(r'Memory mode\s+(\S+)')
    result['memory_mode'] = m.group(1) if m else 'Unknown'

    m = find(r'Total SRAM used\s+([\d.]+)\s+(\S+)')
    result['sram_bytes'] = _vela_size_to_bytes(m.group(1), m.group(2)) if m else None

    m = find(r'Total On-chip Flash used\s+([\d.]+)\s+(\S+)')
    result['flash_bytes'] = _vela_size_to_bytes(m.group(1), m.group(2)) if m else None

    m = find(r'Total Off-chip Flash used\s+([\d.]+)\s+(\S+)')
    result['offchip_flash_bytes'] = _vela_size_to_bytes(m.group(1), m.group(2)) if m else None

    m = find(r'Neural network macs\s+([\d]+)\s+MACs')
    result['mac_count'] = int(m.group(1)) if m else 0

    m = find(r'CPU operators\s*=\s*(\d+)\s*\(([\d.]+)%\)')
    result['cpu_ops'] = int(m.group(1))   if m else 0
    result['cpu_pct'] = float(m.group(2)) if m else 0.0

    m = find(r'NPU operators\s*=\s*(\d+)\s*\(([\d.]+)%\)')
    result['npu_ops'] = int(m.group(1))   if m else 0
    result['npu_pct'] = float(m.group(2)) if m else 0.0

    result['total_ops'] = result['npu_ops'] + result['cpu_ops']
    return result


# =============================================================================
# MACs from TFLite Flatbuffer (CPU path, pure Python)
# Field-access pattern mirrors mcu_compile_tflm.py's parse_tflite_model().
# =============================================================================

def compute_macs_from_tflite(tflite_path: Path) -> int:
    """
    Compute total MAC count by parsing the .tflite flatbuffer directly.

    Formulas (N = batch; every formula counts all output elements):
      CONV_2D                      : N*out_h*out_w*out_ch * kH*kW*in_ch_per_group
      DEPTHWISE_CONV_2D            : N*out_h*out_w*out_ch * kH*kW
      TRANSPOSE_CONV               : N*in_h*in_w*in_ch * out_ch*kH*kW
      CONV_3D                      : N*out_d*out_h*out_w*out_ch * kD*kH*kW*in_ch
      FULLY_CONNECTED              : rows * out_features * in_features
      BATCH_MATMUL                 : output elements * K
      UNIDIRECTIONAL_SEQUENCE_LSTM : steps * (all gate, recurrent and
                                     projection weight elements)

    rows / steps is the number of input vectors the operator applies its
    weights to, e.g. batch * sequence length for a [1, 8, 16] input.

    TRANSPOSE_CONV intentionally uses INPUT spatial dimensions, not output.
    The TFLM/CMSIS-NN reference kernel implements it with a "scatter"
    dataflow that loops over input elements and scatters each input*weight
    product into the output accumulator (see reference/transpose_conv.h).
    Using output dimensions would overcount MACs by roughly stride_h *
    stride_w for any upsampling (stride > 1) layer.

    AVERAGE_POOL_2D and MAX_POOL_2D are intentionally excluded: pooling has
    no multiply-accumulate operations (average pooling is additions plus one
    division per window; max pooling is comparisons only), so folding their
    element count into total_macs would misreport non-MAC work as MACs.

    Custom ops (ethosu) are skipped -- Vela report has their exact MACs.
    """
    data = tflite_path.read_bytes()
    buf = bytearray(data)

    def field(table_offset, field_idx):
        vt_off = table_offset - struct.unpack_from('<i', buf, table_offset)[0]
        vt_size = struct.unpack_from('<H', buf, vt_off)[0]
        if (field_idx + 2) * 2 >= vt_size:
            return 0
        field_rel = struct.unpack_from('<H', buf, vt_off + (field_idx + 2) * 2)[0]
        if field_rel == 0:
            return 0
        return table_offset + field_rel

    def read_vector(offset):
        vec_offset = offset + struct.unpack_from('<I', buf, offset)[0]
        length = struct.unpack_from('<I', buf, vec_offset)[0]
        return vec_offset + 4, length

    def read_string(offset):
        str_offset = offset + struct.unpack_from('<I', buf, offset)[0]
        str_len = struct.unpack_from('<I', buf, str_offset)[0]
        return buf[str_offset + 4:str_offset + 4 + str_len].decode('utf-8', errors='replace')

    root = struct.unpack_from('<I', buf, 0)[0]

    # operator_codes -- field 1 (same as parse_tflite_model)
    oc_field = field(root, 1)
    op_codes = []
    if oc_field:
        oc_start, oc_count = read_vector(oc_field)
        for i in range(oc_count):
            elem = oc_start + i * 4
            table = elem + struct.unpack_from('<I', buf, elem)[0]

            builtin = 0
            bf = field(table, 3)  # builtin_code (int32)
            if bf:
                builtin = struct.unpack_from('<i', buf, bf)[0]
            else:
                dep = field(table, 0)  # deprecated_builtin_code (uint8)
                builtin = struct.unpack_from('<B', buf, dep)[0] if dep else 0

            custom_name = None
            cf = field(table, 1)
            if cf:
                try:
                    custom_name = read_string(cf)
                except Exception:
                    custom_name = None

            op_codes.append((builtin, custom_name))

    # subgraphs -- field 2
    sg_field = field(root, 2)
    if not sg_field:
        return 0

    total_macs = 0
    sg_start, sg_count = read_vector(sg_field)

    for sgi in range(sg_count):
        sg_elem = sg_start + sgi * 4
        sg = sg_elem + struct.unpack_from('<I', buf, sg_elem)[0]

        # tensors -- field 0
        tensors = []
        tf = field(sg, 0)
        if tf:
            t_start, t_count = read_vector(tf)
            for ti in range(t_count):
                te = t_start + ti * 4
                to = te + struct.unpack_from('<I', buf, te)[0]
                sf = field(to, 0)  # shape vector
                shape = []
                if sf:
                    sh_start, sh_count = read_vector(sf)
                    for j in range(sh_count):
                        shape.append(struct.unpack_from('<i', buf, sh_start + j * 4)[0])
                tensors.append(shape)

        # operators -- field 3 (same as parse_tflite_model comment)
        of = field(sg, 3)
        if not of:
            continue
        o_start, o_count = read_vector(of)

        for oi in range(o_count):
            oe = o_start + oi * 4
            op = oe + struct.unpack_from('<I', buf, oe)[0]

            # Operator fields: opcode_index(0), inputs(1), outputs(2)
            ocif = field(op, 0)
            # FlatBuffers omits scalar fields containing their default value.
            # opcode_index defaults to zero, so a missing field selects the
            # first OperatorCode rather than indicating an invalid operator.
            opcode_index = struct.unpack_from('<I', buf, ocif)[0] if ocif else 0
            if opcode_index >= len(op_codes):
                continue
            builtin_code, custom_name = op_codes[opcode_index]
            if custom_name:
                continue  # Custom ops (e.g. ETHOSU) skipped for CPU MAC calc

            inputs = []
            inf = field(op, 1)
            if inf:
                iv_start, iv_count = read_vector(inf)
                for k in range(iv_count):
                    inputs.append(struct.unpack_from('<i', buf, iv_start + k * 4)[0])

            outputs = []
            outf = field(op, 2)
            if outf:
                ov_start, ov_count = read_vector(outf)
                for k in range(ov_count):
                    outputs.append(struct.unpack_from('<i', buf, ov_start + k * 4)[0])

            def sh(idx):
                return tensors[idx] if 0 <= idx < len(tensors) else []

            def numel(shape):
                n = 1
                for d in shape:
                    n *= d
                return n if shape and all(d > 0 for d in shape) else 0

            def rows_of(shape, features):
                # Vectors of length `features` the weights are applied to.
                total = numel(shape)
                return total // features if features > 0 and total % features == 0 else 0

            macs = 0
            out_shape = sh(outputs[0]) if outputs else []

            if builtin_code == 3:     # CONV_2D
                if len(inputs) >= 2:
                    fs_ = sh(inputs[1])
                    if len(out_shape) == 4 and len(fs_) == 4:
                        _, kh, kw, ic = fs_
                        macs = numel(out_shape) * kh * kw * ic

            elif builtin_code == 4:   # DEPTHWISE_CONV_2D
                if len(inputs) >= 2:
                    fs_ = sh(inputs[1])
                    if len(out_shape) == 4 and len(fs_) == 4:
                        _, kh, kw, _ = fs_
                        macs = numel(out_shape) * kh * kw

            elif builtin_code == 67:  # TRANSPOSE_CONV
                # Inputs are (output_shape, filter, input[, bias]); the
                # scatter dataflow means real work scales with the INPUT
                # spatial size, not the (usually larger, upsampled) output.
                if len(inputs) >= 3:
                    fs_ = sh(inputs[1])
                    is_ = sh(inputs[2])
                    if len(fs_) == 4 and len(is_) == 4:
                        oc_, kh, kw, _ = fs_
                        macs = numel(is_) * oc_ * kh * kw

            elif builtin_code == 132:  # CONV_3D
                if len(inputs) >= 2:
                    fs_ = sh(inputs[1])
                    if len(out_shape) == 5 and len(fs_) == 5:
                        kd, kh, kw, ic, _ = fs_
                        macs = numel(out_shape) * kd * kh * kw * ic

            elif builtin_code == 9:   # FULLY_CONNECTED
                if len(inputs) >= 2:
                    ws_ = sh(inputs[1])
                    if len(ws_) == 2:
                        out_f, in_f = ws_
                        macs = rows_of(sh(inputs[0]), in_f) * out_f * in_f

            elif builtin_code == 126:  # BATCH_MATMUL
                # lhs holds M*K values per batch whether or not it is
                # transposed, so K follows from its two innermost dims.
                lhs = sh(inputs[0]) if inputs else []
                if len(lhs) >= 2 and len(out_shape) >= 2 and out_shape[-2] > 0:
                    k = (lhs[-1] * lhs[-2]) // out_shape[-2]
                    macs = numel(out_shape) * k

            elif builtin_code == 44:  # UNIDIRECTIONAL_SEQUENCE_LSTM
                # Inputs 1-8 are gate and recurrent weights, 16 is the
                # optional projection; absent optional tensors are -1.
                in_shape = sh(inputs[0]) if inputs else []
                if in_shape:
                    steps = rows_of(in_shape, in_shape[-1])
                    weights = sum(numel(sh(inputs[i])) for i in list(range(1, 9)) + [16]
                                  if i < len(inputs) and inputs[i] >= 0
                                  and len(sh(inputs[i])) == 2)
                    macs = steps * weights

            # AVERAGE_POOL_2D (1) and MAX_POOL_2D (17) are not multiply-
            # accumulate operations and must not contribute to total_macs.

            total_macs += macs

    return total_macs


