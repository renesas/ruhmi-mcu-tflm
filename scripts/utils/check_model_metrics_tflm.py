def collect_metrics(deploy_dir: Path, suffix: str = None) -> dict:
    """
    Analyze one model output folder and return every metric.

    Raises FileNotFoundError or ValueError when the folder cannot be analyzed.
    MAC counting failures are reported in ``warnings`` instead.
    """
    root = Path(deploy_dir)
    if not root.exists():
        raise FileNotFoundError(f"Directory not found: {deploy_dir}")

    dirs = find_tflm_dirs(root, suffix)
    platform = "NPU" if dirs["is_npu"] else "CPU"
    n_in, n_out = parse_io_info(dirs["model_cc"])
    metrics = {
        "model_dir": str(dirs["root"]),
        "suffix": dirs["suffix"],
        "platform": platform,
        "arena_bytes": int(parse_arena_size(dirs["model_cc"])),
        "flash_bytes": int(parse_model_data_size(dirs["model_data_h"])),
        "mac_count": 0,
        "npu_mac_count": 0,
        "npu_util_pct": 0.0,
        "npu_ops": None,
        "cpu_ops": None,
        "vela_sram_bytes": None,
        "vela_flash_bytes": None,
        "vela_memory_mode": None,
        "vela_accelerator": None,
        "vela_system_config": None,
        "num_inputs": n_in,
        "num_outputs": n_out,
        "registered_ops": parse_op_list(dirs["model_cc"]),
        "tflite_source": str(dirs["tflite_path"]) if dirs["tflite_path"] else None,
        "vela_report": str(dirs["vela_report"]) if dirs["vela_report"] else None,
        "warnings": [],
    }
    if dirs["model_count"] > 1:
        metrics["warnings"].append(
            f"deploy/src holds {dirs['model_count']} models; vela/ and the source "
            "model in this folder are assumed to belong to the selected one.")

    if platform == "NPU":
        vela = parse_vela_report(dirs["vela_report"])
        metrics.update(
            mac_count=int(vela.get("mac_count", 0)),
            npu_util_pct=float(vela.get("npu_pct", 0.0)),
            npu_ops=vela.get("npu_ops"),
            cpu_ops=vela.get("cpu_ops"),
            vela_sram_bytes=vela.get("sram_bytes"),
            vela_flash_bytes=vela.get("flash_bytes"),
            vela_memory_mode=vela.get("memory_mode"),
            vela_accelerator=vela.get("accel_config"),
            vela_system_config=vela.get("sys_config"),
        )
        # Rough split: operator share, not a measure of NPU compute.
        metrics["npu_mac_count"] = int(metrics["mac_count"] * metrics["npu_util_pct"] / 100.0)
        if metrics["cpu_ops"]:
            metrics["warnings"].append(
                f"Vela left {metrics['cpu_ops']} operator(s) on the CPU, so the arena is a "
                "host-side estimate rather than Vela SRAM plus overhead. Measure "
                "GetTensorArenaUsedBytes() on the target.")
    elif dirs["tflite_path"]:
        try:
            metrics["mac_count"] = int(compute_macs_from_tflite(dirs["tflite_path"]))
        except Exception as e:
            metrics["warnings"].append(f"MAC computation failed: {e}")
    else:
        metrics["warnings"].append("No source .tflite found in quantization/ or "
                                   "reference/; MACs are not counted.")
    return metrics


def get_metrics(deploy_dir: Path, suffix: str = None) -> dict:
    """
    Quietly analyze one model output folder and return metrics as a dict.

    Always contains:
        platform (str): "CPU" or "NPU" ("Unknown" on error)
        arena_bytes (int): RAM / Tensor Arena size
        flash_bytes (int): Flash / Model data size
        mac_count (int): Total MAC operations
        npu_mac_count (int): mac_count scaled by the NPU operator share (rough)
        npu_util_pct (float): NPU operator percentage from Vela report (0.0 for CPU)
        error (str or None): Error message if analysis failed

    On success it also contains the other fields of collect_metrics().
    """
    result = {
        "platform": "Unknown",
        "arena_bytes": 0,
        "flash_bytes": 0,
        "mac_count": 0,
        "npu_mac_count": 0,
        "npu_util_pct": 0.0,
        "error": None,
    }
    try:
        result.update(collect_metrics(deploy_dir, suffix))
    except Exception as e:
        result["error"] = str(e)
    return result


def _fmt_bytes(value) -> str:
    return "n/a" if value is None else f"{value:>12,} bytes  ({value / 1024:.1f} KB)"


def parse_memory_stats(deploy_dir: Path, suffix: str = None):
    try:
        m = collect_metrics(deploy_dir, suffix)
    except (FileNotFoundError, ValueError) as e:
        print(f"Error: {e}")
        sys.exit(1)

    platform = m["platform"]
    flash_bytes = m["flash_bytes"]
    mac_count = m["mac_count"]

    print(f"\nMemory Analysis for: {deploy_dir}")
    print("--------------------------------------------------")
    print(f"Platform             : {platform}")
    if m["suffix"]:
        print(f"Suffix               : {m['suffix']}")
    if platform == "NPU":
        print(f"Accelerator          : {m['vela_accelerator'] or '?'}  "
              f"Config: {m['vela_system_config'] or '?'}  "
              f"Mode: {m['vela_memory_mode'] or '?'}")
    print()
    print(f"RAM  (Tensor Arena)  : {_fmt_bytes(m['arena_bytes'])}")
    print(f"Flash (Model/Weights): {flash_bytes:>12,} bytes  ({flash_bytes / 1024 / 1024:.2f} MB)")
    print(f"MAC Operations       : {mac_count:>12,} ops    ({mac_count / 1_000_000:.2f} M)")

    if platform == "NPU" and (m["npu_ops"] or m["cpu_ops"]):
        total_ops = (m["npu_ops"] or 0) + (m["cpu_ops"] or 0)
        print(f"NPU Acceleration     : {m['npu_util_pct']:>11.1f}%      "
              f"({m['npu_ops']} NPU / {total_ops} total ops, {m['cpu_ops']} CPU fallback)")
    elif platform == "CPU":
        print("NPU Acceleration     :           N/A      (CPU-only build)")

    print()
    print(f"Inputs / Outputs     : {m['num_inputs']} input(s), {m['num_outputs']} output(s)")
    ops = m["registered_ops"]
    print(f"Registered Ops ({len(ops):>2})  : {', '.join(ops)}")
    if m["tflite_source"]:
        print(f"TFLite source        : {Path(m['tflite_source']).name}")
    if m["vela_report"]:
        print(f"Vela report          : {m['vela_report']}")
    for w in m["warnings"]:
        print(f"Note: {w}")
    print("--------------------------------------------------\n")

    return (m["arena_bytes"], flash_bytes, mac_count)


def main():
    parser = argparse.ArgumentParser(
        description="Check model metrics for mcu_compile_tflm.py outputs."
    )
    parser.add_argument(
        "deploy_dir", type=Path,
        help="One model output folder, the one containing deploy/ "
             "(e.g. deploy_output/model_NPU_tflm/)"
    )
    parser.add_argument(
        "--suffix", default=None,
        help="Model to analyze when deploy/src holds several (the --suffix it was compiled with)"
    )
    parser.add_argument(
        "--json", action="store_true",
        help="Print the metrics as JSON instead of a table"
    )
    parser.add_argument('--version', '-v', action='version', version=f'%(prog)s {__version__}')
    args = parser.parse_args()
    if args.json:
        metrics = get_metrics(args.deploy_dir, args.suffix)
        print(json.dumps(metrics, indent=2))
        sys.exit(1 if metrics["error"] else 0)
    parse_memory_stats(args.deploy_dir, args.suffix)


